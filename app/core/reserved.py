BUILTIN_RESERVED_WORDS = {
    "oracle": frozenset(_ORACLE),
    "mysql": frozenset(_MYSQL),
    "postgres": frozenset(_POSTGRES),
}


def reserved_words(dialect: str, provider: ReservedWordProvider | None = None) -> frozenset[str]:
    """Return the built-in list combined with optional online lookup results."""
    if dialect not in SUPPORTED_DIALECTS:
        raise ValueError(f"unknown SQL dialect: {dialect}")
    builtin = BUILTIN_RESERVED_WORDS[dialect]
    if provider is None:
        return builtin
    return builtin | frozenset(str(word).upper() for word in provider(dialect))


def fetch_oracle_reserved_words(connection: Any) -> frozenset[str]:
    """Read the connected Oracle server's reserved words from V$RESERVED_WORDS.

    Callers decide how to handle insufficient privileges and retain the built-in
    set. This function does not return driver exception text.
    """
    cursor = connection.cursor()
    try:
        cursor.execute("SELECT KEYWORD FROM V$RESERVED_WORDS WHERE RESERVED = 'Y'")
        return frozenset(str(row[0]).upper() for row in cursor.fetchall() if row and row[0])
    finally:
        try:
            cursor.close()
        except Exception:
            pass
