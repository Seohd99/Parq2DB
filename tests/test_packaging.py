"""Keep pyproject.toml, uv.lock, requirements.txt, and .python-version consistent.

pyproject.toml is the single source of dependency pins. uv.lock and requirements.txt are generated:

    uv lock
    uv export --format requirements-txt --no-hashes --no-emit-project -o requirements.txt
"""

from __future__ import annotations

import re
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
_PIN = re.compile(r"^([A-Za-z0-9._-]+)(?:\[[^\]]*\])?==([^\s;]+)")


def _name(raw: str) -> str:
    return re.sub(r"[-_.]+", "-", raw).lower()


def _pins(specs: list[str]) -> dict[str, str]:
    pins: dict[str, str] = {}
    for spec in specs:
        match = _PIN.match(spec.strip())
        assert match, f"dependency is not pinned with ==: {spec}"
        pins[_name(match.group(1))] = match.group(2)
    return pins


def _pyproject() -> dict:
    return tomllib.loads((ROOT / "pyproject.toml").read_text(encoding="utf-8"))


def _lock() -> dict:
    return tomllib.loads((ROOT / "uv.lock").read_text(encoding="utf-8"))


def test_pyproject_separates_runtime_and_dev_pins() -> None:
    project = _pyproject()
    runtime = _pins(project["project"]["dependencies"])
    dev = _pins(project["dependency-groups"]["dev"])
    assert {"fastapi", "uvicorn", "pyarrow", "duckdb"} <= runtime.keys()
    assert {"pytest", "httpx"} <= dev.keys()
    assert not runtime.keys() & dev.keys()


def test_uv_lock_matches_pyproject_pins() -> None:
    project = _pyproject()
    lock = _lock()
    assert lock["requires-python"] == project["project"]["requires-python"]
    root = next(p for p in lock["package"] if p["name"] == project["project"]["name"])
    metadata = root["metadata"]
    locked_runtime = {_name(d["name"]): d["specifier"].removeprefix("==") for d in metadata["requires-dist"]}
    locked_dev = {_name(d["name"]): d["specifier"].removeprefix("==") for d in metadata["requires-dev"]["dev"]}
    assert locked_runtime == _pins(project["project"]["dependencies"]), "run `uv lock`"
    assert locked_dev == _pins(project["dependency-groups"]["dev"]), "run `uv lock`"


def test_requirements_txt_is_exported_from_uv_lock() -> None:
    text = (ROOT / "requirements.txt").read_text(encoding="utf-8")
    assert text.startswith("# This file was autogenerated by uv")
    exported = {
        _name(m.group(1)): m.group(2)
        for line in text.splitlines()
        if (m := _PIN.match(line))
    }
    locked = {_name(p["name"]): p["version"] for p in _lock()["package"] if "registry" in p["source"]}
    assert exported == locked, "run `uv export --format requirements-txt --no-hashes --no-emit-project -o requirements.txt`"


def test_python_version_file_matches_requires_python() -> None:
    pinned = (ROOT / ".python-version").read_text(encoding="utf-8").strip()
    assert re.fullmatch(r"3\.\d+", pinned)
    assert _pyproject()["project"]["requires-python"] == f">={pinned}"
