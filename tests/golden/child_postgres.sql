CREATE TABLE PB_TEST_DATA (
  ID INTEGER NOT NULL,
  LEVEL VARCHAR(6),
  DATE DATE,
  COMMENT VARCHAR(4922),
  STRUCT_VALUE_CITY VARCHAR(9),
  STRUCT_VALUE_ACTIVE BOOLEAN,
  EVENT_TS TIMESTAMPTZ(6),
  AMOUNT NUMERIC(12,2)
);

CREATE TABLE PB_TEST_DATA_LIST_INT (
  ID INTEGER NOT NULL,
  ORD BIGINT NOT NULL,
  VALUE BIGINT
);

CREATE TABLE PB_TEST_DATA_LIST_DOUBLE (
  ID INTEGER NOT NULL,
  ORD BIGINT NOT NULL,
  VALUE DOUBLE PRECISION
);

CREATE TABLE PB_TEST_DATA_LIST_STRUCT (
  ID INTEGER NOT NULL,
  ORD BIGINT NOT NULL,
  LIST_STRUCT_ITEM_NAME VARCHAR(6),
  LIST_STRUCT_ITEM_SCORE BIGINT
);

CREATE TABLE PB_TEST_DATA_MAP_VALUE (
  ID INTEGER NOT NULL,
  MAP_KEY VARCHAR(2),
  MAP_VALUE INTEGER
);

CREATE TABLE PB_TEST_DATA_NESTED_LIST (
  ID INTEGER NOT NULL,
  ORD BIGINT NOT NULL
);

CREATE TABLE PB_TEST_DATA_NESTED_LIST_ITEM (
  ID INTEGER NOT NULL,
  PARENT_ORD BIGINT NOT NULL,
  ORD BIGINT NOT NULL,
  VALUE INTEGER
);
