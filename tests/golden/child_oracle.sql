CREATE TABLE PB_TEST_DATA (
  ID NUMBER(10) NOT NULL,
  LEVEL_2 VARCHAR2(6 CHAR),
  DATE_2 DATE,
  COMMENT_2 CLOB,
  STRUCT_VALUE_CITY VARCHAR2(9 CHAR),
  STRUCT_VALUE_ACTIVE NUMBER(1),
  EVENT_TS TIMESTAMP(6) WITH TIME ZONE,
  AMOUNT NUMBER(12,2)
);

CREATE TABLE PB_TEST_DATA_LIST_INT (
  ID NUMBER(10) NOT NULL,
  ORD NUMBER(19) NOT NULL,
  VALUE NUMBER(19)
);

CREATE TABLE PB_TEST_DATA_LIST_DOUBLE (
  ID NUMBER(10) NOT NULL,
  ORD NUMBER(19) NOT NULL,
  VALUE BINARY_DOUBLE
);

CREATE TABLE PB_TEST_DATA_LIST_STRUCT (
  ID NUMBER(10) NOT NULL,
  ORD NUMBER(19) NOT NULL,
  LIST_STRUCT_ITEM_NAME VARCHAR2(6 CHAR),
  LIST_STRUCT_ITEM_SCORE NUMBER(19)
);

CREATE TABLE PB_TEST_DATA_MAP_VALUE (
  ID NUMBER(10) NOT NULL,
  MAP_KEY VARCHAR2(2 CHAR),
  MAP_VALUE NUMBER(10)
);

CREATE TABLE PB_TEST_DATA_NESTED_LIST (
  ID NUMBER(10) NOT NULL,
  ORD NUMBER(19) NOT NULL
);

CREATE TABLE PB_TEST_DATA_NESTED_LIST_ITEM (
  ID NUMBER(10) NOT NULL,
  PARENT_ORD NUMBER(19) NOT NULL,
  ORD NUMBER(19) NOT NULL,
  VALUE NUMBER(10)
);
