CREATE TABLE PB_TEST_DATA (
  ID INT NOT NULL,
  LEVEL_2 VARCHAR(6),
  DATE_2 DATE,
  COMMENT_2 VARCHAR(4922),
  STRUCT_VALUE_CITY VARCHAR(9),
  STRUCT_VALUE_ACTIVE TINYINT(1),
  EVENT_TS DATETIME(6),
  AMOUNT DECIMAL(12,2)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE PB_TEST_DATA_LIST_INT (
  ID INT NOT NULL,
  ORD BIGINT NOT NULL,
  VALUE BIGINT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE PB_TEST_DATA_LIST_DOUBLE (
  ID INT NOT NULL,
  ORD BIGINT NOT NULL,
  VALUE DOUBLE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE PB_TEST_DATA_LIST_STRUCT (
  ID INT NOT NULL,
  ORD BIGINT NOT NULL,
  LIST_STRUCT_ITEM_NAME VARCHAR(6),
  LIST_STRUCT_ITEM_SCORE BIGINT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE PB_TEST_DATA_MAP_VALUE (
  ID INT NOT NULL,
  MAP_KEY VARCHAR(2),
  MAP_VALUE INT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE PB_TEST_DATA_NESTED_LIST (
  ID INT NOT NULL,
  ORD BIGINT NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE PB_TEST_DATA_NESTED_LIST_ITEM (
  ID INT NOT NULL,
  PARENT_ORD BIGINT NOT NULL,
  ORD BIGINT NOT NULL,
  VALUE INT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
