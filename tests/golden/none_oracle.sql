CREATE TABLE PB_TEST_DATA (
  ID NUMBER(10) NOT NULL,
  LEVEL_2 VARCHAR2(6 CHAR),
  DATE_2 DATE,
  COMMENT_2 CLOB,
  LIST_INT CLOB CHECK (LIST_INT IS JSON),
  LIST_DOUBLE CLOB CHECK (LIST_DOUBLE IS JSON),
  LIST_STRUCT CLOB CHECK (LIST_STRUCT IS JSON),
  STRUCT_VALUE CLOB CHECK (STRUCT_VALUE IS JSON),
  MAP_VALUE CLOB CHECK (MAP_VALUE IS JSON),
  NESTED_LIST CLOB CHECK (NESTED_LIST IS JSON),
  EVENT_TS TIMESTAMP(6) WITH TIME ZONE,
  AMOUNT NUMBER(12,2)
);
